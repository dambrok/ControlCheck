function htmlPath = export_html(summary, outputPath)
% EXPORT_HTML Generates a clean HTML validation report directly from MATLAB.
%
% Syntax:
%   htmlPath = export_html(summary, outputPath)

    if nargin < 2 || isempty(outputPath)
        thisDir = fileparts(mfilename('fullpath'));
        outputPath = fullfile(thisDir, '..', '..', 'reports', 'validation_report.html');
    end

    [parentDir, ~, ~] = fileparts(outputPath);
    if ~exist(parentDir, 'dir')
        mkdir(parentDir);
    end

    fid = fopen(outputPath, 'w', 'n', 'UTF-8');
    if fid == -1
        error('SimuVerify:FileOpenError', 'Unable to create HTML report: %s', outputPath);
    end
    cleaner = onCleanup(@() fclose(fid));

    outcomes = summary.outcomes;
    total = summary.total_tests;
    passed = summary.passed_tests;
    failed = summary.failed_tests;
    errors = summary.error_tests;
    passPct = summary.pass_percentage;
    durationMs = summary.total_duration_ms;

    % Build table rows
    rowsHtml = '';
    for i = 1:length(outcomes)
        o = outcomes{i};
        stLower = lower(o.status);

        w_exp = '-';
        if isfield(o.expected_values, 'steady_state_speed')
            w_exp = sprintf('%.2f', o.expected_values.steady_state_speed);
        end

        w_act = '-';
        os_act = '-';
        ts_act = '-';
        i_act = '-';
        if isfield(o.actual_metrics, 'steady_state_speed')
            w_act = sprintf('%.2f', o.actual_metrics.steady_state_speed);
            os_act = sprintf('%.2f%%', o.actual_metrics.overshoot_pct);
            ts_act = sprintf('%.3fs', o.actual_metrics.settling_time_s);
            i_act = sprintf('%.2fA', o.actual_metrics.peak_current_a);
        end

        diagHtml = '';
        if ~isempty(o.failure_reasons)
            diagHtml = '<div style="margin-top:6px; color:#f87171; font-size:12px;"><strong>Diagnosis:</strong> ';
            diagHtml = [diagHtml strjoin(o.failure_reasons, '; ') '</div>'];
        end

        row = sprintf(['<tr class="status-%s">\n' ...
                       '  <td><strong>%s</strong></td>\n' ...
                       '  <td>%s%s</td>\n' ...
                       '  <td><span class="badge">%s</span></td>\n' ...
                       '  <td><span class="badge">%s</span></td>\n' ...
                       '  <td><span class="badge badge-%s">%s</span></td>\n' ...
                       '  <td>%s / %s rad/s</td>\n' ...
                       '  <td>%s</td>\n' ...
                       '  <td>%s</td>\n' ...
                       '  <td>%s</td>\n' ...
                       '  <td>%.2f ms</td>\n' ...
                       '</tr>\n'], ...
                       stLower, o.test_id, o.name, diagHtml, o.category, o.severity, ...
                       stLower, o.status, w_act, w_exp, os_act, ts_act, i_act, o.execution_time_ms);
        rowsHtml = [rowsHtml row];
    end

    htmlDoc = sprintf(['<!DOCTYPE html>\n' ...
        '<html lang="en">\n' ...
        '<head>\n' ...
        '  <meta charset="UTF-8">\n' ...
        '  <title>SimuVerify Automated Validation Report (MATLAB)</title>\n' ...
        '  <style>\n' ...
        '    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0f172a; color: #f8fafc; padding: 24px; }\n' ...
        '    .container { max-width: 1200px; margin: 0 auto; }\n' ...
        '    .header { background: #1e293b; padding: 24px; border-radius: 10px; margin-bottom: 20px; border: 1px solid #334155; }\n' ...
        '    h1 { margin: 0 0 8px 0; font-size: 24px; }\n' ...
        '    .kpi-grid { display: grid; grid-template-columns: repeat(auto-fit, minmax(180px, 1fr)); gap: 16px; margin-bottom: 24px; }\n' ...
        '    .kpi { background: #1e293b; border: 1px solid #334155; border-radius: 8px; padding: 16px; }\n' ...
        '    .kpi-title { font-size: 12px; color: #94a3b8; text-transform: uppercase; font-weight: 600; }\n' ...
        '    .kpi-val { font-size: 28px; font-weight: 800; margin-top: 6px; }\n' ...
        '    table { width: 100%; border-collapse: collapse; background: #1e293b; border-radius: 8px; overflow: hidden; }\n' ...
        '    th, td { padding: 12px 14px; text-align: left; border-bottom: 1px solid #334155; font-size: 13px; }\n' ...
        '    th { background: #0f172a; color: #94a3b8; font-size: 11px; text-transform: uppercase; }\n' ...
        '    .badge { padding: 3px 8px; border-radius: 4px; font-size: 11px; font-weight: bold; background: #334155; }\n' ...
        '    .badge-pass { background: rgba(16, 185, 129, 0.2); color: #34d399; }\n' ...
        '    .badge-fail { background: rgba(239, 68, 68, 0.2); color: #f87171; }\n' ...
        '    .badge-error { background: rgba(245, 158, 11, 0.2); color: #fbbf24; }\n' ...
        '    .banner { background: rgba(16, 185, 129, 0.15); border: 1px solid rgba(16, 185, 129, 0.3); color: #a7f3d0; padding: 12px 16px; border-radius: 6px; margin-bottom: 20px; font-size: 13px; }\n' ...
        '  </style>\n' ...
        '</head>\n' ...
        '<body>\n' ...
        '  <div class="container">\n' ...
        '    <div class="header">\n' ...
        '      <h1>SimuVerify Automated Validation Report</h1>\n' ...
        '      <div style="color:#94a3b8; font-size:13px;">Suite: %s | Execution: %.2f ms</div>\n' ...
        '    </div>\n' ...
        '    <div class="banner"><strong>EXECUTION SOURCE:</strong> MATLAB Native Test Runner.</div>\n' ...
        '    <div class="kpi-grid">\n' ...
        '      <div class="kpi"><div class="kpi-title">Total Tests</div><div class="kpi-val">%d</div></div>\n' ...
        '      <div class="kpi"><div class="kpi-title">Passed</div><div class="kpi-val" style="color:#10b981;">%d</div></div>\n' ...
        '      <div class="kpi"><div class="kpi-title">Failed</div><div class="kpi-val" style="color:#ef4444;">%d</div></div>\n' ...
        '      <div class="kpi"><div class="kpi-title">Errors</div><div class="kpi-val" style="color:#f59e0b;">%d</div></div>\n' ...
        '      <div class="kpi"><div class="kpi-title">Pass Rate</div><div class="kpi-val" style="color:#8b5cf6;">%.1f%%</div></div>\n' ...
        '    </div>\n' ...
        '    <table>\n' ...
        '      <thead>\n' ...
        '        <tr><th>ID</th><th>Scenario</th><th>Category</th><th>Severity</th><th>Status</th><th>Speed (Act/Exp)</th><th>Overshoot</th><th>Settling</th><th>Current</th><th>Duration</th></tr>\n' ...
        '      </thead>\n' ...
        '      <tbody>\n' ...
        '        %s\n' ...
        '      </tbody>\n' ...
        '    </table>\n' ...
        '  </div>\n' ...
        '</body>\n' ...
        '</html>\n'], ...
        summary.suite_name, durationMs, total, passed, failed, errors, passPct, rowsHtml);

    fwrite(fid, htmlDoc, 'char');
    htmlPath = outputPath;
end
